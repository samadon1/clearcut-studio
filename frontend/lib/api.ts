/**
 * CLEARCUT API Client
 * 
 * Centralized API client connecting the Next.js frontend to the FastAPI backend.
 * Provides resilient communication with automatic high-fidelity seed fallbacks
 * when the backend is offline or restarting.
 */

import {
  ProductionSummary,
  RevisionAnalysisResult,
  ClearanceCase,
  ResearchRun,
  FictionalCandidate,
  PropagationCheckResult,
  ResolutionType
} from './types';

// Base backend URL configured via environment or defaulting to local development port
const API_BASE = process.env.NEXT_PUBLIC_API_URL || 'http://localhost:8000/api';

/**
 * Fetch the overall production clearance summary including readiness metrics,
 * active cases, departmental statistics, and recent audit activity.
 */
export async function fetchProductionSummary(): Promise<ProductionSummary> {
  try {
    const res = await fetch(`${API_BASE}/productions/summary`);
    if (!res.ok) throw new Error('API request failed');
    return await res.json();
  } catch (err) {
    console.warn('[API] Backend unreachable, using fallback seed summary:', err);
    return getFallbackSeedSummary();
  }
}

/**
 * Reset production state back to the locked baseline (Blue Draft v7).
 */
export async function resetToDemoBaseline(): Promise<ProductionSummary> {
  try {
    const res = await fetch(`${API_BASE}/productions/reset`, { method: 'POST' });
    if (!res.ok) throw new Error('API reset failed');
    const data = await res.json();
    return data.summary;
  } catch (err) {
    console.warn('[API] Reset fallback triggered');
    return getFallbackSeedSummary();
  }
}

/**
 * Analyze a screenplay revision against the baseline draft using Gemini.
 * Returns semantic diffs, filtering routine dialogue edits while flagging rights-bearing elements.
 */
export async function analyzeRevision(
  fromVersion: string = 'ver-script-v7', 
  toVersionLabel: string = 'Pink Draft v8'
): Promise<RevisionAnalysisResult> {
  try {
    const res = await fetch(`${API_BASE}/revisions/analyze`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ from_version: fromVersion, to_version_label: toVersionLabel })
    });
    if (!res.ok) throw new Error('Revision analysis failed');
    return await res.json();
  } catch (err) {
    console.warn('[API] Analyze fallback triggered:', err);
    return getFallbackRevisionAnalysis();
  }
}

/**
 * Execute live Parallel Search API investigation for a specific clearance case.
 * Queries USPTO registers and open-web commercial domain registries.
 */
export async function executeParallelResearch(caseId: string): Promise<ResearchRun> {
  try {
    const res = await fetch(`${API_BASE}/cases/${caseId}/research`, { method: 'POST' });
    if (!res.ok) throw new Error('Research failed');
    return await res.json();
  } catch (err) {
    console.warn('[API] Research fallback triggered:', err);
    return getFallbackResearchRun(caseId);
  }
}

