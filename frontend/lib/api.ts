/**
 * Approve resolution (e.g. Fictionalize to Harbor Brew) and trigger downstream propagation check.
 */
export async function approveResolution(
  caseId: string,
  resolutionType: ResolutionType = 'FICTIONALIZE',
  replacementValue: string = 'Harbor Brew'
): Promise<{ message: string; case: ClearanceCase; propagation: PropagationCheckResult }> {
  try {
    const res = await fetch(`${API_BASE}/cases/${caseId}/resolution/approve`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        resolution_type: resolutionType,
        replacement_value: replacementValue,
        approved_by: 'Production Clearance Supervisor'
      })
    });
    if (!res.ok) throw new Error('Approve resolution failed');
    return await res.json();
  } catch (err) {
    console.warn('[API] Approve fallback triggered:', err);
    return getFallbackResolutionApproval(caseId, replacementValue);
  }
}

